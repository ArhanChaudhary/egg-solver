/// The small lookup tables of the move/index hot path in one static, so that
/// all their accesses share one base register (x86 has no RIP-relative
/// indexed addressing: separate statics cost an `lea` each per use; part of
/// m3-hht's +3.5% at 48T when added). Aligned to a 4 KiB page so its
/// placement relative to pages and cache sets is the same in every build
/// (it moved with unrelated edits before; neutral on its own, see the commit).
#[repr(C, align(4096))]
pub struct HotTables {
    /// Shuffle of each move.
    pub moves: [Aligned32; 18],
    /// Orientation part of each move (the `ORIENT_BITS` term of `compose`).
    pub move_orients: [Aligned32; 18],
    /// Each move's inverse (for `premove_inverse`).
    pub inverse_moves: [Aligned32; 18],
    /// Edge-only conjugation tables (see `coord::edge_key_sym`; 128 bytes
    /// per symmetry: the entry's offset is a scaled index).
    pub sym_edges: [SymEdge; 48],
    /// `coord::CO_LOW`, `coord::CO_HIGH`.
    pub co_low: [u32; 256],
    pub co_high: [u32; 64],
    /// `co_low`, `co_high` and `rank8` (of tetrad masks) times 3: the byte
    /// offset of a packed cocsep entry (`coord::cocsep_x3`).
    pub co_low_x3: [u32; 256],
    pub co_high_x3: [u32; 64],
    pub tetrads_x3: [u8; 256],
    /// `coord::ESLOT` indexed by the complement (in 12 bits) of the mask.
    pub eslot_complement: [u16; 4096],
    /// `coord::RANK8`.
    pub rank8: [u8; 256],
    /// `pext` masks of `coord::cocsep` (read from memory: no 64-bit
    /// immediates per call): orientations of corners 0..6, tetrads.
    pub co_pext_mask: u64,
    pub tetrad_pext_mask: u64,
    /// `lanes::STAT_PAIRS`.
    pub stat_pairs: [f32; 256],
    /// `solver::ALLOWED_AFTER`.
    pub allowed_after: [u32; 6],
    /// `!(7 << (3 * f))`: all moves but those of face `f`.
    pub face_keep: [u32; 6],
    /// Face (`mv / 3`), kind (`mv % 3`) and `face_keep` of the face, by
    /// move (one load each instead of a division).
    pub move_face: [u8; 18],
    pub move_kind: [u8; 18],
    pub move_keep: [u32; 18],
    /// `Cube::child_lookup` masks by move: all ones for X moves (quarter
    /// turns `mv % 3 == 0`, looked up on the other side first), else 0.
    pub x_move_mask: [u32; 18],
}

/// Times 3, for `HotTables::co_low_x3` and `co_high_x3`.
const fn times3<const N: usize>(table: [u32; N]) -> [u32; N] {
    let mut result = [0u32; N];
    let mut i = 0;
    while i < N {
        result[i] = 3 * table[i];
        i += 1;
    }
    result
}

pub static HOT_TABLES: HotTables = HotTables {
    moves: MOVES,
    move_orients: MOVE_ORIENTS,
    inverse_moves: INVERSE_MOVES,
    sym_edges: SYM_EDGES,
    co_low: crate::coord::CO_LOW,
    co_high: crate::coord::CO_HIGH,
    co_low_x3: times3(crate::coord::CO_LOW),
    co_high_x3: times3(crate::coord::CO_HIGH),
    tetrads_x3: {
        // (Only masks of 4 corners occur; the others keep the 0xFF marker.)
        let mut result = [0xFFu8; 256];
        let mut i = 0;
        while i < 256 {
            if crate::coord::RANK8_CONST[i] != 0xFF {
                result[i] = 3 * crate::coord::RANK8_CONST[i];
            }
            i += 1;
        }
        result
    },
    eslot_complement: {
        let mut result = [0u16; 4096];
        let mut mask = 0;
        while mask < 4096 {
            result[mask] = crate::coord::ESLOT_CONST[mask ^ 0xFFF];
            mask += 1;
        }
        result
    },
    rank8: crate::coord::RANK8_CONST,
    co_pext_mask: 0x0060_6060_6060_6060,
    tetrad_pext_mask: 0x0404_0404_0404_0404,
    stat_pairs: crate::lanes::STAT_PAIRS,
    allowed_after: crate::solver::ALLOWED_AFTER_CONST,
    face_keep: {
        let mut result = [0u32; 6];
        let mut face = 0;
        while face < 6 {
            result[face] = !(7 << (3 * face));
            face += 1;
        }
        result
    },
    move_face: {
        let mut result = [0u8; 18];
        let mut mv = 0u8;
        while mv < 18 {
            result[mv as usize] = mv / 3;
            mv += 1;
        }
        result
    },
    move_kind: {
        let mut result = [0u8; 18];
        let mut mv = 0u8;
        while mv < 18 {
            result[mv as usize] = mv % 3;
            mv += 1;
        }
        result
    },
    x_move_mask: {
        let mut result = [0u32; 18];
        let mut mv = 0;
        while mv < 18 {
            result[mv] = if mv.is_multiple_of(3) { !0 } else { 0 };
            mv += 1;
        }
        result
    },
    move_keep: {
        let mut result = [0u32; 18];
        let mut mv = 0;
        while mv < 18 {
            result[mv] = !(7 << (3 * (mv / 3)));
            mv += 1;
        }
        result
    },
};

/// A cube state in one AVX2 register (layout: see the module docs).
#[derive(Clone, Copy)]
#[repr(transparent)]
pub struct Cube(pub __m256i);

/// Load 32 aligned bytes.
#[inline(always)]
pub(crate) fn load(bytes: &Aligned32) -> __m256i {
    unsafe { _mm256_load_si256(std::ptr::from_ref(bytes).cast()) }
}

/// 32 bytes from four little-endian 64-bit words (as `_mm256_set_epi64x`,
/// lowest word first).
const fn from_words(words: [i64; 4]) -> Aligned32 {
    let mut bytes = [0u8; 32];
    let mut i = 0;
    while i < 32 {
        bytes[i] = words[i / 8].to_le_bytes()[i % 8];
        i += 1;
    }
    Aligned32(bytes)
}

/// Orientation bits of corners (twist) and edges (flip).
static ORIENT_BITS: Aligned32 =
    from_words([0x6060_6060_6060_6060, 0, 0x1010_1010_1010_1010, 0x1010_1010]);
/// Subtracted after adding orientations; `min` keeps the result if the
/// subtraction wrapped: twists 3..5 become 0..2, flip 2 becomes 0.
static ORIENT_WRAP: Aligned32 =
    from_words([0x6060_6060_6060_6060, 0, 0x2020_2020_2020_2020, 0x2020_2020]);
/// The bytes that hold pieces.
static USED_BYTES: Aligned32 = from_words([-1, 0, -1, 0xFFFF_FFFF]);
/// Corner twist bits.
static CORNER_ORIENT_BITS: Aligned32 = from_words([0x6060_6060_6060_6060, 0, 0, 0]);
static SOLVED_BYTES: Aligned32 =
    from_words([0x0706_0504_0302_0100, 0, 0x0706_0504_0302_0100, 0x0B0A_0908]);

impl Cube {
    #[inline(always)]
    #[must_use]
    pub fn solved() -> Cube {
        Cube(load(&SOLVED_BYTES))
    }

    #[must_use]
    pub fn from_cubie(cube: &CubieCube) -> Cube {
        let mut bytes = Aligned32([0; 32]);
        for i in 0..8 {
            bytes.0[i] = cube.corner_perm[i] | (cube.corner_orient[i] << 5);
        }
        for i in 0..12 {
            bytes.0[16 + i] = cube.edge_perm[i] | (cube.edge_orient[i] << 4);
        }
        Cube(load(&bytes))
    }

    /// The cube with these 32 bytes (in the layout above).
    #[must_use]
    pub fn from_bytes(bytes: [u8; 32]) -> Cube {
        Cube(load(&Aligned32(bytes)))
    }

    /// The 32 bytes, with the unused ones zeroed.
    #[must_use]
    pub fn to_bytes(self) -> [u8; 32] {
        let mut bytes = Aligned32([0; 32]);
        unsafe {
            let used = _mm256_and_si256(self.0, load(&USED_BYTES));
            _mm256_store_si256(std::ptr::from_mut(&mut bytes).cast(), used);
        }
        bytes.0
    }

    #[must_use]
    pub fn to_cubie(self) -> CubieCube {
        let bytes = self.to_bytes();
        let mut cube = CubieCube::SOLVED;
        for (i, &byte) in bytes[..8].iter().enumerate() {
            cube.corner_perm[i] = byte & 7;
            cube.corner_orient[i] = byte >> 5;
        }
        for (i, &byte) in bytes[16..28].iter().enumerate() {
            cube.edge_perm[i] = byte & 15;
            cube.edge_orient[i] = (byte >> 4) & 1;
        }
        cube
    }

    /// "`self` then `other`".
    #[inline(always)]
    #[must_use]
    pub fn compose(self, other: Cube) -> Cube {
        unsafe {
            let moved = _mm256_shuffle_epi8(self.0, other.0);
            let other_orient = _mm256_and_si256(other.0, load(&ORIENT_BITS));
            let sum = _mm256_add_epi8(moved, other_orient);
            let wrapped = _mm256_sub_epi8(sum, load(&ORIENT_WRAP));
            // Bytes outside USED_BYTES are left as garbage (they never feed
            // back into used bytes); `equals` and `to_bytes` mask them. (Part
            // of m1-micro's +2.2% at 48T.)
            Cube(_mm256_min_epu8(sum, wrapped))
        }
    }

    /// This cube followed by move `mv`.
    #[inline(always)]
    #[must_use]
    pub fn apply_move(self, mv: Move) -> Cube {
        // SAFETY: a `Move` is below 18.
        unsafe { self.apply_move_unchecked(mv.index()) }
    }

    /// `apply_move` without the bounds check of the move tables (for the
    /// search loops, whose moves come from move masks).
    ///
    /// # Safety
    /// `mv < 18`.
    #[inline(always)]
    #[must_use]
    pub unsafe fn apply_move_unchecked(self, mv: usize) -> Cube {
        // `compose` with the move's orientation term precomputed (2-3 µops
        // less per child; part of m1-micro's +2.2% at 48T).
        // SAFETY: `mv < 18` (the caller's contract); AVX2 is enabled.
        unsafe {
            let moved = _mm256_shuffle_epi8(self.0, load(HOT_TABLES.moves.get_unchecked(mv)));
            let sum = _mm256_add_epi8(moved, load(HOT_TABLES.move_orients.get_unchecked(mv)));
            let wrapped = _mm256_sub_epi8(sum, load(&ORIENT_WRAP));
            Cube(_mm256_min_epu8(sum, wrapped))
        }
    }

    /// Given the inverse of a cube `c` (`self`), the inverse of `c` followed
    /// by move `mv`: the inverse move applied *before* `self`.
    #[inline(always)]
    #[must_use]
    pub fn premove_inverse(self, mv: Move) -> Cube {
        // SAFETY: a `Move` is below 18.
        unsafe { self.premove_inverse_unchecked(mv.index()) }
    }

    /// `premove_inverse` without the bounds check of the move table.
    ///
    /// # Safety
    /// `mv < 18`.
    #[inline(always)]
    #[must_use]
    pub unsafe fn premove_inverse_unchecked(self, mv: usize) -> Cube {
        // SAFETY: `mv < 18` (the caller's contract).
        Cube(load(unsafe { HOT_TABLES.inverse_moves.get_unchecked(mv) })).compose(self)
    }

    /// Negate the corner twists (mod 3), i.e. swap twists 1 and 2: the two
    /// twist bits trade places.
    #[inline(always)]
    #[must_use]
    pub fn negate_corner_orient(self) -> Cube {
        unsafe {
            let twists = _mm256_and_si256(self.0, load(&CORNER_ORIENT_BITS));
            let left = _mm256_slli_epi32(twists, 1);
            let right = _mm256_srli_epi32(twists, 1);
            let swapped = _mm256_and_si256(_mm256_or_si256(left, right), load(&CORNER_ORIENT_BITS));
            let rest = _mm256_xor_si256(self.0, twists);
            Cube(_mm256_or_si256(rest, swapped))
        }
    }

    /// Inverse cube (vcube's method). The permutation part is `c^27719`,
    /// computed by an addition chain of shuffles: 27720 = lcm(1, ..., 12) is
    /// a multiple of the order of every permutation of 12 or fewer pieces.
    /// Then the orientations are moved and negated. (Not measured
    /// separately.)
    #[inline(always)]
    #[must_use]
    pub fn inverse(self) -> Cube {
        unsafe {
            let c = self.0;
            let sh = |a, b| _mm256_shuffle_epi8(a, b);
            let c3 = sh(sh(c, c), c);
            let mut p = sh(c3, c3);
            p = sh(p, p);
            p = sh(p, p);
            p = sh(p, c3);
            p = sh(p, p);
            p = sh(p, p);
            p = sh(p, p);
            p = sh(p, p);
            p = sh(p, c);
            p = sh(p, p);
            p = sh(p, p);
            p = sh(p, p);
            p = sh(p, p);
            p = sh(p, p);
            p = sh(p, c3);
            p = sh(p, p);
            p = sh(p, c);
            let orient = load(&ORIENT_BITS);
            let orients = sh(_mm256_and_si256(c, orient), p);
            let pieces = _mm256_andnot_si256(orient, p);
            let result = _mm256_and_si256(_mm256_or_si256(pieces, orients), load(&USED_BYTES));
            Cube(result).negate_corner_orient()
        }
    }

    /// Equal states (the unused bytes are ignored).
    #[inline(always)]
    #[must_use]
    pub fn equals(self, other: Cube) -> bool {
        unsafe {
            let diff = _mm256_xor_si256(self.0, other.0);
            _mm256_testz_si256(diff, load(&USED_BYTES)) != 0
        }
    }

    #[inline(always)]
    #[must_use]
    pub fn is_solved(self) -> bool {
        self.equals(Cube::solved())
    }

    /// Conjugate by symmetry `sym` (as `cubie::conjugate`).
    #[inline(always)]
    #[must_use]
    pub fn transform(self, sym: usize) -> Cube {
        let result = self.transform_edges(sym);
        if SYM_MIRROR[sym] {
            result.negate_corner_orient()
        } else {
            result
        }
    }

    /// Conjugate by symmetry `sym`; only the edges are guaranteed correct
    /// (mirrors leave the corner twists negated).
    #[inline(always)]
    #[must_use]
    pub fn transform_edges(self, sym: usize) -> Cube {
        Cube(load(&SYM_CUBES[sym]))
            .compose(self)
            .compose(Cube(load(&SYM_CUBE_INVERSES[sym])))
    }

    /// `if condition { if_true } else { if_false }`, as a byte blend (no
    /// branch; part of skip-sibling's +13.6% at 48T).
    #[inline(always)]
    #[must_use]
    pub fn select(condition: bool, if_true: Cube, if_false: Cube) -> Cube {
        let mask = unsafe { _mm256_set1_epi8(-i8::from(condition)) };
        unsafe { Cube(_mm256_blendv_epi8(if_false.0, if_true.0, mask)) }
    }

    /// `select` by a mask that is all ones (`if_set`) or all zeros
    /// (`if_clear`). With AVX-512 the mask, e.g. loaded from a table, is the
    /// blend's mask register as is (no mask computation).
    #[must_use]
    #[inline(always)]
    pub fn select_mask(mask: u32, if_set: Cube, if_clear: Cube) -> Cube {
        #[cfg(target_feature = "avx512bw")]
        // SAFETY: AVX-512BW is enabled (cfg).
        unsafe {
            Cube(_mm256_mask_blend_epi8(mask, if_clear.0, if_set.0))
        }
        #[cfg(not(target_feature = "avx512bw"))]
        Cube::select(mask != 0, if_set, if_clear)
    }

    /// The cube that move `mv`'s child looks up first, for a node with cubes
    /// `moved` and `other`: `other.premove_inverse(mv)` for an X move
    /// (`x_move_mask` all ones), else `moved.apply_move(mv)` (`x_move_mask`
    /// 0). One composition of selected operands instead of both cubes and a
    /// select (`apply_move` is `compose` with the move's shuffle).
    ///
    /// # Safety
    /// `mv < 18`.
    #[must_use]
    #[inline(always)]
    pub unsafe fn child_lookup(moved: Cube, other: Cube, mv: usize, x_move_mask: u32) -> Cube {
        // SAFETY: `mv < 18` (the caller's contract).
        let (inverse_move, move_cube) = unsafe {
            (
                Cube(load(HOT_TABLES.inverse_moves.get_unchecked(mv))),
                Cube(load(HOT_TABLES.moves.get_unchecked(mv))),
            )
        };
        let left = Cube::select_mask(x_move_mask, inverse_move, moved);
        let right = Cube::select_mask(x_move_mask, other, move_cube);
        left.compose(right)
    }

    /// Low 64 bits: the 8 corner bytes.
    #[inline(always)]
    #[must_use]
    pub fn corners_u64(self) -> u64 {
        unsafe { _mm_cvtsi128_si64(_mm256_castsi256_si128(self.0)).cast_unsigned() }
    }
}

impl std::fmt::Debug for Cube {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{:?}", self.to_cubie())
    }
}

impl PartialEq for Cube {
    fn eq(&self, other: &Cube) -> bool {
        Cube::equals(*self, *other)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::cubie::*;

    #[test]
    fn simd_matches_cubie() {
        let mut rng = Rng(5);
        let syms = symmetries();
        // (Fewer under Miri, which is slow.)
        for _ in 0..if cfg!(miri) { 20 } else { 200 } {
            let a = CubieCube::random(&mut rng);
            let b = CubieCube::random(&mut rng);
            let (sa, sb) = (Cube::from_cubie(&a), Cube::from_cubie(&b));
            assert_eq!(sa.to_cubie(), a);
            assert_eq!(sa.compose(sb).to_cubie(), a.compose(&b));
            assert_eq!(sa.inverse().to_cubie(), a.inverse());
            for (mv, m) in (0..18).zip(Move::ALL) {
                assert_eq!(sa.apply_move(m).to_cubie(), a.apply_move(m));
                assert_eq!(
                    sa.inverse().premove_inverse(m).to_cubie(),
                    a.apply_move(m).inverse()
                );
                let (inverse_a, inverse_b) = (sa.inverse(), sb.inverse());
                // SAFETY: `mv < 18`.
                let lookup =
                    |moved, other, mask| unsafe { Cube::child_lookup(moved, other, mv, mask) };
                assert_eq!(lookup(sa, inverse_b, 0), sa.apply_move(m));
                assert_eq!(lookup(sa, inverse_b, !0), inverse_b.premove_inverse(m));
                assert_eq!(lookup(inverse_a, sb, !0), sb.premove_inverse(m));
                // SAFETY: `mv < 18`.
                unsafe {
                    assert_eq!(sa.apply_move_unchecked(mv), sa.apply_move(m));
                    assert_eq!(sa.premove_inverse_unchecked(mv), sa.premove_inverse(m));
                }
            }
            for (t, sym) in syms.iter().enumerate() {
                assert_eq!(sa.transform(t).to_cubie(), conjugate(&a, sym));
            }
        }
        assert!(Cube::from_cubie(&CubieCube::SOLVED).is_solved());
    }
}
