//! Fast cube representation: one AVX2 register (32 bytes).
//!
//! Bytes 0..8 hold corners (`piece | twist << 5`), bytes 16..28 hold edges
//! (`piece | flip << 4`); everything else is unspecified (zero for cubes
//! built from cubies, garbage after `compose`).
//!
//! Composition is a single `vpshufb` (byte shuffle: byte `i` of the result
//! is byte `b[i]` of `a`) plus an orientation fix-up (method from vcube):
//! the shuffle moves each piece with its orientation, the orientations of
//! the second cube are added, and a subtract-and-unsigned-min wraps them
//! back into range.

use crate::cubie::{CubieCube, Move};
#[cfg(target_feature = "avx512bw")]
use std::arch::x86_64::_mm256_mask_blend_epi8;
use std::arch::x86_64::{
    __m256i, _mm256_add_epi8, _mm256_and_si256, _mm256_andnot_si256, _mm256_blendv_epi8,
    _mm256_castsi256_si128, _mm256_load_si256, _mm256_min_epu8, _mm256_or_si256, _mm256_set1_epi8,
    _mm256_shuffle_epi8, _mm256_slli_epi32, _mm256_srli_epi32, _mm256_store_si256, _mm256_sub_epi8,
    _mm256_testz_si256, _mm256_xor_si256, _mm_cvtsi128_si64,
};

/// 32 bytes, aligned for AVX2 loads.
#[repr(C, align(32))]
#[derive(Clone, Copy)]
pub struct Aligned32(pub [u8; 32]);

/// 64 bytes on one cache line.
#[repr(C, align(64))]
#[derive(Clone, Copy)]
pub struct Aligned64(pub [u8; 64]);

// Move and symmetry constants generated by build.rs from `cubie`:
// `MOVES`, `MOVE_ORIENTS`, `INVERSE_MOVES`, `SYM_CUBES`, `SYM_CUBE_INVERSES`,
// `SYM_EDGES`, `SYM_MIRROR`, `SYM_INVERSES`, `SYM_MOVE_MAP`.

/// One symmetry's edge-conjugation vectors (see `coord::edge_parts_sym`):
/// the piece classes of T, the position permutation Tinv, and Tinv's eo by
/// source position; padded to 128 bytes, so that an entry's offset is a
/// scaled index.
#[repr(C, align(128))]
#[derive(Clone, Copy)]
pub struct SymEdge {
    pub classes: Aligned32,
    pub perm: Aligned32,
    pub perm_eo: Aligned32,
    pub pad: Aligned32,
}

