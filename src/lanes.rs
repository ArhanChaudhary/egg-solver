                    for mv in &mut moves {
                        let candidates: Vec<u32> =
                            (0..18).filter(|&m| allowed >> m & 1 != 0).collect();
                        let m = candidates[rng.next_u64() as usize % candidates.len()];
                        *mv = m as u8;
                        allowed = ALLOWED_AFTER[(m / 3) as usize];
                    }
