//! Lane-interleaved IDA* for throughput.
//!
//! Each thread runs several independent "lanes"; each lane solves its own
//! cube with an explicit-stack DFS that generates one child at a time and
//! stops whenever it needs a table lookup: it computes the index, issues a
//! prefetch and yields. Lanes are visited round-robin; a visit first
//! resolves the lookup issued on the previous visit (the other side's value
//! first, then the moved side's), then advances the lane to its next lookup.
//! With 16 lanes each miss gets a whole round (~0.5us) of slack while only
//! ~one miss per lane is in flight.
//!
//! Since children are generated one at a time, sibling-face pruning skips
//! the lookups of pruned siblings entirely.
//!
//! The search logic (masks, tight-bound tricks, side choice, sibling
//! pruning, back-jumps, job ordering) mirrors `solver.rs`.

use crate::cubie::{inverse_move, CubieCube};
use crate::simd::Cube;
use crate::solver::{Solver, Stats, ALLOWED_AFTER, ALL_MOVES, NO_HALF};

const MAXD: usize = 26;

#[derive(Clone, Copy)]
struct Node {
    c: Cube,
    ci: Cube,
    ln: u8,
    li: u8,
    mm_n: u32,
    mm_i: u32,
    /// Moves still to try on the chosen side.
    todo: u32,
    /// Remaining moves.
    r: u8,
    /// Whether children are generated by moving the normal cube.
    normal: bool,
    /// Best known lower bound over the children of each face.
    fmax: [u8; 6],
    /// Lower bound on this node's distance learned from children.
    lb: u8,
    /// Move that led here, and whether it was applied to the normal cube.
    m: u8,
    m_normal: bool,
    /// Other-side value of the X and X' children of each face (0xFF if not
    /// yet known). They are equal: H X = H X' because X2 is in H, and the
    /// other side's coordinate only depends on the coset H X^-1 b.
    tw: [u8; 6],
}

#[derive(Clone, Copy)]
struct Job {
    moves: [u8; 4],
    len: u8,
    ln: u8,
    li: u8,
    stat: f32,
}

#[inline(always)]
fn job_weight(j: &Job) -> f32 {
    if (j.moves[j.len as usize - 1] / 3) % 2 == 0 {
        47525.0
    } else {
        58206.0
    }
}

/// Job statistic contribution of a lookup value h: 8^(16-h). Steeper than
/// cube48opt's 2^(12-h); measured ~2% fewer nodes (saturating beyond 8^).
const fn mk_heur_terms() -> [f32; 64] {
    let mut t = [0f32; 64];
    let mut h = 0;
    while h < 64 {
        let mut v = 1f32;
        let mut i = h;
        while i < 16 {
            v *= 8.0;
            i += 1;
        }
        let mut i = 16;
        while i < h {
            v /= 8.0;
            i += 1;
        }
        t[h] = v;
        h += 1;
    }
    t
}
static HEUR_TERMS: [f32; 64] = mk_heur_terms();

#[derive(Clone, Copy, PartialEq, Eq)]
enum Phase {
    Idle,
    /// Waiting for the lookup of the non-moved side.
    WaitOther,
    /// Waiting for the lookup of the moved side.
    WaitMoved,
}

pub struct Lane {
    active: bool,
    pub cube_index: usize,
    root_c: Cube,
    root_ci: Cube,
    jobs: Vec<Job>,
    job_pos: usize,
    target: u8,
    stack: [Node; MAXD],
    sp: usize,
    phase: Phase,
    // pending child
    k_a: Cube,
    k_b: Cube,
    k_m: u8,
    k_idx: u64,
    k_cd: u8,
    k_po: u8,
    heur: f32,
    pub stats: Stats,
    pub solution: Vec<u8>,
}

enum Step {
    Pending,
    Found,
}

impl Lane {
    fn new() -> Lane {
        let n = Node {
            c: Cube::solved(),
            ci: Cube::solved(),
            ln: 0,
            li: 0,
            mm_n: 0,
            mm_i: 0,
            todo: 0,
            r: 0,
            normal: true,
            fmax: [0; 6],
            lb: 0,
            m: 0,
            m_normal: true,
            tw: [0xFF; 6],
        };
        Lane {
            active: false,
            cube_index: 0,
            root_c: Cube::solved(),
            root_ci: Cube::solved(),
            jobs: Vec::new(),
            job_pos: 0,
            target: 0,
            stack: [n; MAXD],
            sp: 0,
            phase: Phase::Idle,
            k_a: Cube::solved(),
            k_b: Cube::solved(),
            k_m: 0,
            k_idx: 0,
            k_cd: 0,
            k_po: 0,
            heur: 0.0,
            stats: Stats::default(),
            solution: Vec::new(),
        }
    }

    fn job_cubes(&self, j: &Job) -> (Cube, Cube) {
        let mut c = self.root_c;
        let mut ci = self.root_ci;
        for &m in &j.moves[..j.len as usize] {
            c = c.apply_move(m as usize);
            ci = ci.premove_inv(m as usize);
        }
        (c, ci)
    }

    /// Start solving a cube. Returns true if it is already solved.
    fn start(&mut self, s: &Solver, cube: &CubieCube, index: usize) -> bool {
        self.active = true;
        self.cube_index = index;
        self.stats = Stats::default();
        self.solution.clear();
        self.phase = Phase::Idle;
        let c = Cube::from_cubie(cube);
        if c.is_solved() {
            return true;
        }
        self.root_c = c;
        self.root_ci = c.inverse();
        let ln = s.lower_bound(c);
        let li = s.lower_bound(self.root_ci);
        self.jobs.clear();
        self.jobs.push(Job {
            moves: [0; 4],
            len: 0,
            ln,
            li,
            stat: 0.0,
        });
        self.target = ln.max(li).max(1);
        self.start_iteration(s);
        false
    }

    fn extend_jobs(&mut self, s: &Solver) {
        let mut out = Vec::with_capacity(self.jobs.len() * 15);
        for j in &self.jobs {
            let mm = if j.len == 0 {
                ALL_MOVES
            } else {
                ALLOWED_AFTER[(j.moves[j.len as usize - 1] / 3) as usize]
            };
            let mut mmv = mm;
            while mmv != 0 {
                let m = mmv.trailing_zeros() as u8;
                mmv &= mmv - 1;
                let mut n = *j;
                n.moves[n.len as usize] = m;
                n.len += 1;
                out.push(n);
            }
        }
        // bounds, with batched prefetch
        for chunk in out.chunks_mut(32) {
            let mut idx = [(0u64, 0u8); 64];
            for (n, j) in chunk.iter().enumerate() {
                let (c, ci) = self.job_cubes(j);
                idx[2 * n] = s.index(c);
                idx[2 * n + 1] = s.index(ci);
                s.prefetch(idx[2 * n].0);
                s.prefetch(idx[2 * n + 1].0);
            }
            for (n, j) in chunk.iter_mut().enumerate() {
                j.ln = s.value(idx[2 * n].0, idx[2 * n].1);
                j.li = s.value(idx[2 * n + 1].0, idx[2 * n + 1].1);
            }
        }
        self.jobs = out;
    }

    fn start_iteration(&mut self, s: &Solver) {
        loop {
            let jl = s.job_len(self.target);
            while (self.jobs[0].len as usize) < jl {
                self.extend_jobs(s);
            }
            if jl > 0 {
                self.jobs
                    .sort_by(|a, b| (b.stat * job_weight(b)).total_cmp(&(a.stat * job_weight(a))));
            }
            self.job_pos = 0;
            if self.setup_job() {
                return;
            }
            self.target += 1;
        }
    }

    /// Set up the root node of the next feasible job starting at `job_pos`.
    /// Returns false if the iteration is exhausted.
    fn setup_job(&mut self) -> bool {
        while self.job_pos < self.jobs.len() {
            let j = self.jobs[self.job_pos];
            let r = self.target - j.len;
            self.heur = 0.0;
            let (c, ci) = self.job_cubes(&j);
            if j.ln > r || j.li > r || (j.len > 0 && c.is_solved()) {
                self.jobs[self.job_pos].stat = 0.0;
                self.job_pos += 1;
                continue;
            }
            let mut mm_n = if j.len == 0 {
                ALL_MOVES
            } else {
                ALLOWED_AFTER[(j.moves[j.len as usize - 1] / 3) as usize]
            };
            let mut mm_i = ALL_MOVES;
            if j.li == r {
                mm_n &= NO_HALF;
            }
            if j.ln == r {
                mm_i &= NO_HALF;
            }
            self.sp = 0;
            self.stack[0] = make_node(c, ci, j.ln, j.li, mm_n, mm_i, r, 0, true);
            return true;
        }
        false
    }

    /// Advance until a lookup is pending or a solution is found.
    #[inline(always)]
    fn advance(&mut self, s: &Solver) -> Step {
        let maxval = s.base + 3;
        loop {
            let sp = self.sp;
            let node = &mut self.stack[sp];
            if node.lb > node.r || node.todo == 0 {
                let (lb, m) = (node.lb, node.m);
                if sp == 0 {
                    // job finished
                    self.jobs[self.job_pos].stat = self.heur;
                    self.job_pos += 1;
                    if !self.setup_job() {
                        self.target += 1;
                        self.start_iteration(s);
                    }
                    continue;
                }
                self.sp -= 1;
                let p = &mut self.stack[self.sp];
                let f = (m / 3) as usize;
                p.fmax[f] = p.fmax[f].max(lb);
                p.lb = p.lb.max(lb.saturating_sub(1));
                continue;
            }
            let m = node.todo.trailing_zeros() as usize;
            node.todo &= node.todo - 1;
            let face = m / 3;
            let r1 = node.r - 1;
            if node.fmax[face] > r1 + 1 {
                node.todo &= !(7 << (3 * face));
                continue;
            }
            self.stats.nodes += 1;
            let (a, b, lo) = if node.normal {
                (node.c, node.ci, node.li)
            } else {
                (node.ci, node.c, node.ln)
            };
            if r1 == 0 {
                // nodes with r == 1 always move the normal cube
                if a.apply_move(m).is_solved() {
                    self.k_m = m as u8;
                    return Step::Found;
                }
                continue;
            }
            let a2 = a.apply_move(m);
            let b2 = b.premove_inv(m);
            let half = m % 3 == 1;
            if r1 > maxval {
                let po = if half { lo } else { 0 };
                if po > r1 || a2.is_solved() {
                    continue;
                }
                self.k_a = a2;
                self.k_b = b2;
                self.k_m = m as u8;
                self.push_child(0, po);
                continue;
            }
            self.k_a = a2;
            self.k_b = b2;
            self.k_m = m as u8;
            if half {
                // other side's coset is unchanged by a half turn
                if lo > r1 {
                    self.note_value(face, lo);
                    continue;
                }
                let (idx, cd) = s.index(a2);
                if cd > r1 {
                    self.note_value(face, cd);
                    continue;
                }
                self.k_po = lo;
                self.k_idx = idx;
                self.k_cd = cd;
                s.prefetch(idx);
                self.phase = Phase::WaitMoved;
                return Step::Pending;
            }
            let tw = self.stack[self.sp].tw[face];
            if tw != 0xFF {
                // X' child: the other side's value is the X child's.
                if tw > r1 {
                    self.note_value(face, tw);
                    continue;
                }
                let (idx, cd) = s.index(a2);
                if cd > r1 {
                    self.note_value(face, cd.max(tw));
                    continue;
                }
                self.k_po = tw;
                self.k_idx = idx;
                self.k_cd = cd;
                s.prefetch(idx);
                self.phase = Phase::WaitMoved;
                return Step::Pending;
            }
            let (idx, cd) = s.index(b2);
            if cd > r1 {
                self.stack[self.sp].tw[face] = cd;
                self.note_value(face, cd);
                continue;
            }
            self.k_idx = idx;
            self.k_cd = cd;
            s.prefetch(idx);
            self.phase = Phase::WaitOther;
            return Step::Pending;
        }
    }

    /// Record a value learned for a child on `face` of the top node.
    #[inline(always)]
    fn note_value(&mut self, face: usize, v: u8) {
        let node = &mut self.stack[self.sp];
        node.fmax[face] = node.fmax[face].max(v);
        node.lb = node.lb.max(v.saturating_sub(1));
    }

    #[inline(always)]
    fn resolve_other(&mut self, s: &Solver) {
        self.stats.lookups += 1;
        let po = s.value(self.k_idx, self.k_cd);
        let r1 = self.stack[self.sp].r - 1;
        let face = (self.k_m / 3) as usize;
        self.stack[self.sp].tw[face] = po;
        if po > r1 {
            self.note_value(face, po);
            self.phase = Phase::Idle;
            return;
        }
        let (idx, cd) = s.index(self.k_a);
        if cd > r1 {
            self.note_value(face, cd.max(po));
            self.phase = Phase::Idle;
            return;
        }
        self.k_po = po;
        self.k_idx = idx;
        self.k_cd = cd;
        s.prefetch(idx);
        self.phase = Phase::WaitMoved;
    }

    #[inline(always)]
    fn resolve_moved(&mut self, s: &Solver) {
        self.stats.lookups += 1;
        self.phase = Phase::Idle;
        let pm = s.value(self.k_idx, self.k_cd);
        let po = self.k_po;
        self.heur += HEUR_TERMS[po.min(63) as usize] + HEUR_TERMS[pm.min(63) as usize];
        let r1 = self.stack[self.sp].r - 1;
        let face = (self.k_m / 3) as usize;
        self.note_value(face, pm.max(po));
        if pm > r1 || self.k_a.is_solved() {
            return;
        }
        self.push_child(pm, po);
    }

    /// Push the pending child (`k_a`, `k_b`, `k_m`) with bounds for the moved
    /// side (`pm`) and the other side (`po`).
    #[inline(always)]
    fn push_child(&mut self, pm: u8, po: u8) {
        let node = &self.stack[self.sp];
        let r1 = node.r - 1;
        let face = (self.k_m / 3) as usize;
        let (c, ci, ln, li, mut mm_n, mut mm_i) = if node.normal {
            (self.k_a, self.k_b, pm, po, ALLOWED_AFTER[face], node.mm_i)
        } else {
            (self.k_b, self.k_a, po, pm, node.mm_n, ALLOWED_AFTER[face])
        };
        if li == r1 {
            mm_n &= NO_HALF;
        }
        if ln == r1 {
            mm_i &= NO_HALF;
        }
        let child = make_node(c, ci, ln, li, mm_n, mm_i, r1, self.k_m, node.normal);
        self.sp += 1;
        self.stack[self.sp] = child;
    }

    fn reconstruct(&self) -> Vec<u8> {
        let j = &self.jobs[self.job_pos];
        let mut normal: Vec<u8> = j.moves[..j.len as usize].to_vec();
        let mut pre: Vec<u8> = Vec::new();
        for n in &self.stack[1..=self.sp] {
            if n.m_normal {
                normal.push(n.m);
            } else {
                pre.push(n.m);
            }
        }
        normal.push(self.k_m);
        for &m in pre.iter().rev() {
            normal.push(inverse_move(m));
        }
        normal
    }
}

#[allow(clippy::too_many_arguments)]
#[inline(always)]
fn make_node(
    c: Cube,
    ci: Cube,
    ln: u8,
    li: u8,
    mm_n: u32,
    mm_i: u32,
    r: u8,
    m: u8,
    m_normal: bool,
) -> Node {
    let (normal, todo) = if r == 1 {
        (true, mm_n & mm_i)
    } else if mm_n.count_ones() <= mm_i.count_ones() {
        (true, mm_n)
    } else {
        (false, mm_i)
    };
    Node {
        c,
        ci,
        ln,
        li,
        mm_n,
        mm_i,
        todo,
        r,
        normal,
        fmax: [0; 6],
        lb: 0,
        m,
        m_normal,
        tw: [0xFF; 6],
    }
}

/// Solve cubes `cubes(i)` for i taken from the shared counter `next`, with
/// `nlanes` interleaved lanes on this thread. Calls `done(index, solution,
/// stats, seconds)` for every solved cube. Stops when `cubes` returns None
/// for all lanes or when `stop` is set.
pub fn run_lanes(
    s: &Solver,
    cubes: &(dyn Fn(usize) -> Option<CubieCube> + Sync),
    next: &std::sync::atomic::AtomicUsize,
    stop: &std::sync::atomic::AtomicBool,
    nlanes: usize,
    mut done: impl FnMut(usize, Vec<u8>, Stats, f64),
) {
    use std::sync::atomic::Ordering::Relaxed;
    use std::time::Instant;
    let mut lanes: Vec<Lane> = (0..nlanes).map(|_| Lane::new()).collect();
    let mut started = vec![Instant::now(); nlanes];
    // Give lane `li` a new cube; returns false if there are none left.
    let fetch =
        |l: &mut Lane, t: &mut Instant, done: &mut dyn FnMut(usize, Vec<u8>, Stats, f64)| -> bool {
            loop {
                let i = next.fetch_add(1, Relaxed);
                let Some(cube) = cubes(i) else {
                    l.active = false;
                    return false;
                };
                *t = Instant::now();
                if l.start(s, &cube, i) {
                    done(i, vec![], Stats::default(), 0.0);
                    continue;
                }
                return true;
            }
        };
    let mut nactive = 0;
    for (l, t) in lanes.iter_mut().zip(started.iter_mut()) {
        if fetch(l, t, &mut done) {
            nactive += 1;
        }
    }
    // Single-pass round-robin: each visit resolves the lookup the lane
    // issued one round earlier, then advances it to its next lookup. Every
    // lane has one miss in flight with a whole round of slack.
    while nactive > 0 && !stop.load(Relaxed) {
        for li in 0..nlanes {
            let l = &mut lanes[li];
            if !l.active {
                continue;
            }
            match l.phase {
                Phase::WaitOther => {
                    l.resolve_other(s);
                    if l.phase != Phase::Idle {
                        continue;
                    }
                }
                Phase::WaitMoved => l.resolve_moved(s),
                Phase::Idle => {}
            }
            if let Step::Found = l.advance(s) {
                let sol = l.reconstruct();
                let dt = started[li].elapsed().as_secs_f64();
                done(l.cube_index, sol, l.stats, dt);
                if !fetch(l, &mut started[li], &mut done) {
                    nactive -= 1;
                }
            }
        }
    }
}
