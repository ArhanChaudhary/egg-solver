//! Portable cube backend (aarch64 NEON, wasm SIMD128, scalar fallback): the
//! cube as two 16-byte vectors, with the same byte layout, operations and
//! results as the x86 backend (`simd.rs`), so that tables and searches are
//! identical on every backend.
//!
//! `corners` holds bytes 0..16 (corners in 0..8: `piece | twist << 5`),
//! `edges` bytes 16..32 (edges in 0..12: `piece | flip << 4`). The x86 code
//! shuffles both halves with one 32-byte `vpshufb`, which works per 16-byte
//! lane: here the halves are shuffled separately. Where an index byte
//! carries orientation bits, it is masked to its piece first (`vpshufb`
//! ignores bits 4..6 of an index; `tbl` returns 0 for indices from 16).
//! Only the vector operations differ per target (`V16`); this file and
//! `coord.rs` are shared.

